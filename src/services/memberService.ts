export async function getMemberData(
  slug: string
): Promise<IMemberDetail | null> {
  // Simulate CMS fetch delay
  await new Promise((resolve) => setTimeout(resolve, 100));

  const member = temporaryMemberData.find((m) => m.slug === slug);
  return member ? { ...member } : null;
}

export async function getAllMembers(): Promise<IMemberDetail[]> {
  await new Promise((resolve) => setTimeout(resolve, 100));
  return [...temporaryMemberData];
}

export async function getCurrentMembers(): Promise<IMemberDetail[]> {
  const members = await getAllMembers();
  return members.filter((member) =>
    member.details.some(
      (detail) => detail.label === "STATUS" && detail.value === "Active"
    )
  );
}

export async function getPastMembers(): Promise<IMemberDetail[]> {
  const members = await getAllMembers();
  return members.filter((member) =>
    member.details.some(
      (detail) => detail.label === "STATUS" && detail.value === "Former"
    )
  );
}
